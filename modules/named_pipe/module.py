"""Nagios-compatible external command file (named pipe) for Shinken.

Python 3 port of the historical ``mod-named-pipe`` module. Loaded by the
arbiter (or a receiver), it creates a FIFO (``command_file``, usually
``nagios.cmd``) and reads the external commands written into it, one per
line, in the Nagios format::

    [1700000000] SCHEDULE_FORCED_SVC_CHECK;host;service;1700000000

Each line is handed to the daemon as an
:class:`shinken.external_command.ExternalCommand`, exactly like the
commands received through Livestatus. Scripts, Thruk/Nagios CGIs in
"command file" mode, NSCA bridges, check_mk... can therefore keep writing
to the command file.

When ``command_file`` is set in ``shinken.cfg`` and no ``named_pipe``
module is declared on the arbiter, the arbiter instantiates this module
automatically (``NamedPipe-Autogenerated``).
"""

import errno
import os
import select
import stat

from shinken.basemodule import BaseModule
from shinken.external_command import ExternalCommand
from shinken.log import logger

properties = {
    'daemons': ['arbiter', 'receiver'],
    'type': 'named_pipe',
    'external': True,
    'worker_capable': False,
}

DEFAULT_COMMAND_FILE = '/var/lib/shinken/nagios.cmd'
READ_SIZE = 65536
# A command line longer than this without a newline is garbage: drop it
# instead of growing the buffer forever.
MAX_LINE_LENGTH = 1024 * 1024


def get_instance(plugin):
    """Called by the modules manager to build the module instance."""
    path = getattr(plugin, 'command_file', '') or ''
    if not path:
        logger.warning("[NamedPipe] Module %s has no command_file parameter, using %s",
                       plugin.get_name(), DEFAULT_COMMAND_FILE)
        path = DEFAULT_COMMAND_FILE
    logger.info("[NamedPipe] Get a named pipe module for plugin %s (%s)",
                plugin.get_name(), path)
    return NamedPipe(plugin, path)


def decode_command(raw):
    """Decode one command line read from the pipe (UTF-8, else latin-1)."""
    try:
        line = raw.decode('utf-8')
    except UnicodeDecodeError:
        line = raw.decode('latin-1')
    return line.strip()


class CommandBuffer(object):
    """Split the bytes read from the pipe into complete command lines."""

    def __init__(self):
        self.pending = b''

    def feed(self, data):
        """Add ``data`` and return the list of complete, decoded, non-empty lines."""
        self.pending += data
        *lines, self.pending = self.pending.split(b'\n')
        if len(self.pending) > MAX_LINE_LENGTH:
            logger.warning("[NamedPipe] Dropping a %d bytes command without end of line",
                           len(self.pending))
            self.pending = b''
        result = []
        for raw in lines:
            line = decode_command(raw)
            if line:
                result.append(line)
        return result


class NamedPipe(BaseModule):
    """External module reading Nagios external commands from a FIFO."""

    def __init__(self, modconf, path):
        BaseModule.__init__(self, modconf)
        self.pipe_path = path
        self.fifo = None
        # Our own writer end: while it is open, the reader never sees an
        # end-of-file when the external writers close the pipe, so we do
        # not have to re-open the FIFO after each command.
        self._keepalive_fd = None
        self.buffer = CommandBuffer()

    def create_fifo(self):
        """(Re)create the FIFO at ``pipe_path`` with mode 0660."""
        directory = os.path.dirname(os.path.abspath(self.pipe_path))
        os.makedirs(directory, exist_ok=True)
        try:
            mode = os.lstat(self.pipe_path).st_mode
        except FileNotFoundError:
            mode = None
        if mode is not None:
            if not stat.S_ISFIFO(mode):
                logger.warning("[NamedPipe] %s exists and is not a named pipe, replacing it",
                               self.pipe_path)
            os.unlink(self.pipe_path)
        os.mkfifo(self.pipe_path, 0o660)
        # mkfifo is subject to the umask: enforce the group write access the
        # web interfaces and scripts of the shinken group rely on.
        os.chmod(self.pipe_path, 0o660)

    def open(self):
        """Create and open the FIFO; return the read file descriptor or None."""
        self.close()
        try:
            self.create_fifo()
            self.fifo = os.open(self.pipe_path, os.O_RDONLY | os.O_NONBLOCK)
            self._keepalive_fd = os.open(self.pipe_path, os.O_WRONLY | os.O_NONBLOCK)
        except OSError as exp:
            logger.error("[NamedPipe] Cannot create the named pipe %s: %s",
                         self.pipe_path, exp)
            self.close()
            return None
        logger.info("[%s] The named pipe '%s' is open", self.get_name(), self.pipe_path)
        return self.fifo

    def close(self):
        for attr in ('_keepalive_fd', 'fifo'):
            fd = getattr(self, attr)
            if fd is not None:
                try:
                    os.close(fd)
                except OSError:
                    pass
                setattr(self, attr, None)

    def get(self):
        """Read what is available and return the ExternalCommand list."""
        commands = []
        while True:
            try:
                data = os.read(self.fifo, READ_SIZE)
            except BlockingIOError:
                break
            except OSError as exp:
                if exp.errno in (errno.EAGAIN, errno.EINTR):
                    break
                raise
            if not data:
                break
            commands.extend(ExternalCommand(line) for line in self.buffer.feed(data))
            if len(data) < READ_SIZE:
                break
        return commands

    def do_loop_turn(self, timeout=1.0):
        """Wait up to ``timeout`` seconds for commands and queue them."""
        if self.fifo is None:
            if self.open() is None:
                return 0
        try:
            readable, _, _ = select.select([self.fifo], [], [], timeout)
        except (OSError, ValueError) as exp:
            logger.error("[NamedPipe] select() on %s failed: %s", self.pipe_path, exp)
            self.close()
            return 0
        if not readable:
            return 0
        commands = self.get()
        for command in commands:
            logger.debug("[NamedPipe] Got external command: %s", command.cmd_line)
            self.from_q.put(command)
        return len(commands)

    def main(self):
        """Main loop of the module process."""
        self.set_proctitle(self.name)
        self.set_exit_handler()
        self.open()
        while not self.interrupted:
            if self.fifo is None and self.open() is None:
                # Creation failed: retry later without spinning.
                for _ in range(10):
                    if self.interrupted:
                        break
                    select.select([], [], [], 1)
                continue
            self.do_loop_turn()

    def do_stop(self):
        """Close and remove the FIFO so that writers fail instead of blocking."""
        self.close()
        try:
            if stat.S_ISFIFO(os.lstat(self.pipe_path).st_mode):
                os.unlink(self.pipe_path)
        except OSError:
            pass
        logger.info("[%s] Named pipe %s closed", self.get_name(), self.pipe_path)
